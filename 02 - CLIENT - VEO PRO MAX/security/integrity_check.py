# NOTE:
# Do not self-hash this file from the inline manifest above. Any edit to the
# embedded hash values changes this file's bytes, which makes the expected hash
# self-contradictory. If self-verification is needed, the manifest must live in
# an external file signed/generated at build time.
#
# Build-time integrity hash file (generated by build_release.py)
