def verify_startup_integrity() -> dict:
    """
    Verify integrity of critical files at startup.

    Returns:
        {
            'passed': bool,
            'checked': int,
            'failures': list[str],  # filenames that failed
            'skipped': bool,        # True if no hashes configured (dev mode)
        }
    """
    result = {
        'passed': True,
        'checked': 0,
        'failures': [],
        'skipped': False,
    }

    # In development mode (no hashes configured), skip check
    if not CRITICAL_FILES:
        result['skipped'] = True
        log.debug("[Integrity] Dev mode - no hashes configured, skipping check")
        return result

    # Dev-mode detection: running from source tree (not compiled)
    # In dev mode, integrity mismatches are logged but NOT enforced
    # because source files change during development.
    _is_dev_mode = not (getattr(sys, 'frozen', False) or '__compiled__' in dir())

    for rel_path, expected_hash in CRITICAL_FILES.items():
        # Skip files with placeholder hashes (not yet regenerated by build)
        if expected_hash.startswith("PLACEHOLDER"):
            log.debug(f"[Integrity] SKIP {rel_path}: placeholder hash (rebuild needed)")
            continue

        filepath = _APP_ROOT / rel_path
        actual_hash = _hash_file(filepath)
        result['checked'] += 1

        if actual_hash != expected_hash:
            if _is_dev_mode:
                # Dev mode: log warning but don't fail (source may be edited)
                log.info(
                    f"[Integrity] DEV MISMATCH (ignored): {rel_path} "
                    f"(expected={expected_hash[:16]}..., got={actual_hash[:16]}...)"
                )
            else:
                # Production: real tamper detection
                result['passed'] = False
                result['failures'].append(rel_path)
                log.warning(
                    f"[Integrity] MISMATCH: {rel_path} "
                    f"(expected={expected_hash[:16]}..., got={actual_hash[:16]}...)"
                )

    if result['passed']:
        log.debug(f"[Integrity] All {result['checked']} files verified OK")
    else:
        log.critical(
            f"[Integrity] FAILED: {len(result['failures'])} "
            f"of {result['checked']} files tampered: {result['failures']}"
        )

    return result


def compute_all_hashes() -> Dict[str, str]:
    """
    Compute hashes of all security files.
    Used by build_release.py to populate CRITICAL_FILES dict.

    Returns:
        Dict[relative_path, sha256_hash]
    """
    security_dir = _APP_ROOT / "security"
    hashes = {}

    critical_patterns = [
        "license_client.py",
        "firebase_rest_client.py",
        "trial_protection.py",
        "_encrypted_keys.py",
        "_encrypted_api_keys.py",
        "anti_tamper.py",
    ]

    # Also hash runtime modules outside security/
    runtime_modules = [
        ("services", "permissions.py"),
    ]

    for filename in critical_patterns:
        filepath = security_dir / filename
        if filepath.exists():
            rel = f"security/{filename}"
            hashes[rel] = _hash_file(filepath)

    for subdir, filename in runtime_modules:
        filepath = _APP_ROOT / subdir / filename
        if filepath.exists():
            rel = f"{subdir}/{filename}"
            hashes[rel] = _hash_file(filepath)

    return hashes
